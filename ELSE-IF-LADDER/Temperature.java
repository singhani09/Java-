class Temperature{
    public static void main(String[] args){
        int tempa = 45;
        if(tempa>=40){
            System.out.println("Very hot");
        }
        else if (tempa >=30){
            System.out.println("Hot");
        }
        else if (tempa >=20){
            System.out.println("Warm");
        }
        else if (tempa>=10){
            System.out.println("Cold");
        }
        else {
            System.out.println("cold");
        }
    }
}
    
    
